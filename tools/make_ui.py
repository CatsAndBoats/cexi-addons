"""Builds ui.lua, the auction house addon's drawing kit, out of the Party Finder addon's helper functions so the two look
the same. Functions are copied by name; the animation state they kept in `st` moves to a module table."""
import os, re, sys
# run from anywhere: python tools/make_ui.py [out]; the source is Party Finder's addon in this repo
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'addons', 'vanacore', 'partyfinder-vanacore', 'partyfinder-vanacore.lua')
OUT = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, 'addons', 'vanacore', 'auctionhouse-vanacore', 'ui.lua')
lines = open(SRC).read().split('\n')

def func(name):
    """the lines of `local function name(`, to its closing `end` at column 0"""
    for i, l in enumerate(lines):
        if l.startswith('local function %s(' % name):
            if l.rstrip().endswith(' end') and l.count(' function ') == 1 and ' end' in l[l.index(')'):]:
                return [l]
            j = i + 1
            while lines[j] != 'end': j += 1
            return lines[i:j + 1]
    raise SystemExit('no function ' + name)

def block(start_pat, end_pat):
    s = next(i for i, l in enumerate(lines) if re.match(start_pat, l))
    e = next(i for i in range(s, len(lines)) if re.match(end_pat, lines[i]))
    return lines[s:e + 1]

def fix(ls):
    out = []
    for l in ls:
        l = re.sub(r'\bst\.', 'A.', l)
        l = l.replace("vana.paths.addon .. '\\\\fonts\\\\'", "vana.paths.addon .. '\\\\fonts\\\\'")
        out.append(l)
    return out

