"""Builds exits.lua for the VanaMaps addon: where each zone's ways into its neighbours are, so the map can mark them and
open the neighbour's map at a click. From the server's sql/zonelines.sql (zoneline, fromzone, tozone, tox, toy, toz):
a line says where you arrive in `tozone`, not where its doorway is in `fromzone`, so a zone's way to a neighbour is put
where the line coming back the other way sets you down, which is just inside that doorway.

Which floor (map) of a zone with several a doorway is on can't be told from the table: the game works it out from the
zone's collision. tools/vanamaps_exit_floors.json holds what the game said for each, gathered once by visiting the zones
(through the addon's C.ways_floors_here, asked over VanaCore's MCP); a doorway not in it is learnt by the addon the first time the player has the map open in
that zone.   python tools/make_vanamaps_exits.py <server checkout>"""
import json, os, re, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SERVER = sys.argv[1] if len(sys.argv) > 1 else os.path.expanduser('~/catseyexi')
sql = open(os.path.join(SERVER, 'sql', 'zonelines.sql')).read()
rows = [(int(a), int(b), int(c), float(x), float(y), float(z))
        for a, b, c, x, y, z in re.findall(r"VALUES \((\d+),(\d+),(\d+),(-?[\d.]+),(-?[\d.]+),(-?[\d.]+),\d+\)", sql)]
floors_path = os.path.join(ROOT, 'tools', 'vanamaps_exit_floors.json')
floors = json.load(open(floors_path)) if os.path.exists(floors_path) else {}

# zone -> its ways out: { (x, y on the map's plane, height, to) }. The line (from B, to A, arriving at P) gives zone A a
# way to B at P. Lines within one zone and the Mog House's (zone 0) are left out.
exits = {}
for _, frm, to, x, h, y in sorted(rows):
    if frm == to or frm == 0 or to == 0:
        continue
    exits.setdefault(to, []).append((round(x, 1), round(y, 1), round(h, 1), frm))

def key(zone, e):
    return '%d:%.1f:%.1f' % (zone, e[0], e[1])

out = ['-- Each zone\'s ways into its neighbours: { x, y, height, the zone it leads to[, the floor it is on] }, where the line',
       '-- from that neighbour sets you down. Generated by tools/make_vanamaps_exits.py from the server\'s sql/zonelines.sql',
       '-- and tools/vanamaps_exit_floors.json; edit there.',
       'return {']
n = known = 0
for zone in sorted(exits):
    parts = []
    for e in sorted(set(exits[zone]), key=lambda e: (e[3], e[0], e[1])):
        f = floors.get(key(zone, e))
        n += 1
        known += f is not None
        parts.append('{ %s, %s, %s, %d%s }' % (('%g' % e[0]), ('%g' % e[1]), ('%g' % e[2]), e[3], '' if f is None else ', %d' % f))
    out.append('    [%d] = { %s },' % (zone, ', '.join(parts)))
out += ['}', '']
open(os.path.join(ROOT, 'addons', 'vanacore', 'vanamaps-vanacore', 'exits.lua'), 'w').write('\n'.join(out))
print('exits.lua written: %d ways out of %d zones, %d with a floor from vanamaps_exit_floors.json' % (n, len(exits), known))
